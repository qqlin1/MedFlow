#Requires -Version 5.1
<#
.SYNOPSIS
    MedFlow 一键启动：自动生成 .env（如缺失），构建镜像，启动 MySQL 与应用，等待健康后打印入口。

.DESCRIPTION
    首次运行会下载 Maven 依赖并编译，耗时几分钟；之后再运行只重建有变化的部分。

.PARAMETER Down
    停止并删除容器（保留数据库数据卷）。

.PARAMETER Reset
    停止并删除容器与数据卷（数据库清空，下次启动会重新执行 Flyway 迁移）。

.PARAMETER NoBuild
    不重新构建镜像，直接用已有镜像启动。

.EXAMPLE
    .\docker-start.ps1
    .\docker-start.ps1 -Down
    .\docker-start.ps1 -Reset
#>
[CmdletBinding()]
param(
    [switch]$Down,
    [switch]$Reset,
    [switch]$NoBuild,
    [switch]$OpenBrowser
)

# docker 会把进度信息写到 stderr，PowerShell 5.1 在 Stop 模式下会把它当成异常中断脚本。
# 因此这里保持 Continue，改用 $LASTEXITCODE 显式判断成败。
$ErrorActionPreference = 'Continue'

try { [Console]::OutputEncoding = [System.Text.Encoding]::UTF8 } catch { }

Set-Location -Path $PSScriptRoot

function Write-Step($message) {
    Write-Host "==> $message" -ForegroundColor Cyan
}

function Write-Ok($message) {
    Write-Host "    $message" -ForegroundColor Green
}

function New-RandomBase64Key {
    $bytes = New-Object byte[] 32
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    } finally {
        $generator.Dispose()
    }
    return [Convert]::ToBase64String($bytes)
}

function New-RandomPassword {
    $alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
    $chars = New-Object char[] 24
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $buffer = New-Object byte[] 24
        $rng.GetBytes($buffer)
        for ($i = 0; $i -lt 24; $i++) {
            $chars[$i] = $alphabet[$buffer[$i] % $alphabet.Length]
        }
    } finally {
        $rng.Dispose()
    }
    return -join $chars
}

# ---------- 前置检查 ----------
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw '未找到 docker 命令，请先安装 Docker Desktop 并启动。'
}

docker info --format '{{.ServerVersion}}' 2>$null | Out-Null
if ($LASTEXITCODE -ne 0) {
    throw 'Docker 守护进程未运行，请先启动 Docker Desktop。'
}

# ---------- 停止 / 重置 ----------
if ($Reset) {
    Write-Step '停止容器并删除数据卷'
    docker compose down -v
    if ($LASTEXITCODE -ne 0) { throw '停止失败，请检查 docker 输出。' }
    Write-Ok '已清空，下次启动会重新执行 Flyway 迁移'
    return
}

if ($Down) {
    Write-Step '停止容器（保留数据卷）'
    docker compose down
    if ($LASTEXITCODE -ne 0) { throw '停止失败，请检查 docker 输出。' }
    Write-Ok '已停止'
    return
}

# ---------- 生成 .env ----------
$envPath = Join-Path $PSScriptRoot '.env'
if (-not (Test-Path $envPath)) {
    $existingDataVolume = docker volume ls --quiet --filter 'name=^medflow-mysql-data$'
    if ($LASTEXITCODE -ne 0) { throw '无法检查已有数据库卷，请检查 Docker 状态。' }
    if ($existingDataVolume) {
        throw '已有 medflow-mysql-data 数据卷但 .env 缺失。请恢复原 .env 中的数据库密码，不能为旧数据库生成新密码；不要清空数据卷。'
    }
    Write-Step '未找到 .env，生成随机密码与 JWT 密钥'
    $content = @(
        '# generated by docker-start.ps1 - do not commit',
        ('MEDFLOW_DB_PASSWORD=' + (New-RandomPassword)),
        ('MEDFLOW_JWT_SECRET=' + (New-RandomBase64Key)),
        'MEDFLOW_APP_PORT=8080',
        'MEDFLOW_MYSQL_PORT=3307',
        'MEDFLOW_DEMO_ACCOUNTS_ENABLED=true',
        'MEDFLOW_EXPIRATION_ENABLED=true',
        'MEDFLOW_OPENAPI_ENABLED=true',
        'MEDFLOW_JAVA_OPTS=-XX:MaxRAMPercentage=75'
    )
    # 无 BOM 的 UTF-8：带 BOM 时 docker compose 可能把 BOM 当成第一个键的一部分
    [System.IO.File]::WriteAllLines(
        $envPath,
        [string[]]$content,
        (New-Object System.Text.UTF8Encoding($false))
    )
    Write-Ok ".env 已生成：$envPath"
} else {
    Write-Ok '.env 已存在，沿用现有配置'
}

# ---------- 启动 ----------
if ($NoBuild) {
    Write-Step '启动容器（不重新构建）'
    docker compose up -d --no-build
} else {
    Write-Step '构建镜像并启动容器（首次会下载依赖，请耐心等待）'
    docker compose up -d --build
}

if ($LASTEXITCODE -ne 0) {
    throw 'docker compose 启动失败，请查看上方日志。'
}

# ---------- 等待健康 ----------
Write-Step '等待应用就绪'
$healthy = $false
for ($i = 0; $i -lt 90; $i++) {
    Start-Sleep -Seconds 2
    $status = docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' medflow-app 2>$null
    if ($status -eq 'healthy') {
        $healthy = $true
        break
    }
    if ($status -eq 'unhealthy' -or $status -eq 'exited') {
        Write-Host ''
        docker compose logs --tail 40 app
        throw '应用未能正常启动，已输出最后 40 行日志。'
    }
    Write-Host '.' -NoNewline
}
Write-Host ''

if (-not $healthy) {
    docker compose logs --tail 40 app
    throw '等待超时（约 3 分钟），应用仍未就绪。'
}

# ---------- 读取实际端口并验证业务就绪 ----------
# 以容器实际映射为准，支持 .env 带引号的值以及宿主环境变量覆盖。
$appBinding = docker compose port app 8080
if ($LASTEXITCODE -ne 0 -or $appBinding -notmatch ':(\d+)\s*$') { throw '无法读取应用端口。' }
$appPort = $Matches[1]
$mysqlBinding = docker compose port mysql 3306
if ($LASTEXITCODE -ne 0 -or $mysqlBinding -notmatch ':(\d+)\s*$') { throw '无法读取数据库端口。' }
$mysqlPort = $Matches[1]
$baseUrl = "http://127.0.0.1:$appPort"
try {
    $demoConfig = Invoke-RestMethod -Uri "$baseUrl/api/v1/auth/demo-config" -TimeoutSec 10
    if ($demoConfig.code -ne 'SUCCESS') { throw '配置接口未就绪' }
} catch { throw '无法读取演示配置；请查看应用日志，更新代码后需先运行 docker-start.ps1 构建新镜像。' }
$demoEnabled = $demoConfig.data.enabled -eq $true
if ($demoEnabled) {
    Write-Step '验证三角色登录、数据库连接与医生档案'
    $demoReady = $false
    for ($attempt = 0; $attempt -lt 15; $attempt++) {
        try {
            foreach ($check in @(
                @{Username='admin'; Path='/api/v1/admin/departments'},
                @{Username='doctor'; Path='/api/v1/doctor/schedules'},
                @{Username='patient'; Path='/api/v1/patient/departments'}
            )) {
                $loginJson = @{username=$check.Username;password='123456'} | ConvertTo-Json -Compress
                $loginResult = Invoke-RestMethod -Uri "$baseUrl/api/v1/auth/login" -Method Post -ContentType 'application/json' -Body $loginJson -TimeoutSec 10
                if ($loginResult.code -ne 'SUCCESS' -or -not $loginResult.data.accessToken) { throw '登录未就绪' }
                $roleResult = Invoke-RestMethod -Uri ($baseUrl + $check.Path) -Headers @{Authorization=('Bearer ' + $loginResult.data.accessToken)} -TimeoutSec 10
                if ($roleResult.code -ne 'SUCCESS') { throw '业务接口未就绪' }
            }
            $demoReady = $true
            break
        } catch { Start-Sleep -Seconds 2 }
    }
    if (-not $demoReady) {
        docker compose logs --tail 40 app
        throw '三角色业务验证失败，请检查初始化与数据库连接；数据卷已保留。'
    }
    Write-Ok '三账号登录和角色业务接口均正常'
}

# ---------- 打印入口 ----------

Write-Host ''
Write-Host '  MedFlow 已启动' -ForegroundColor Green
Write-Host '  ------------------------------------------------'
Write-Host "  前端 / 应用   http://127.0.0.1:$appPort/"
Write-Host "  接口文档      http://127.0.0.1:$appPort/swagger-ui/index.html"
Write-Host "  MySQL        127.0.0.1:$mysqlPort  (root / 密码见 .env)"
Write-Host ''
if ($demoEnabled) {
    Write-Host '  演示账号'
    Write-Host '    管理员  admin   / 123456'
    Write-Host '    医生    doctor  / 123456'
    Write-Host '    患者    patient / 123456'
} else { Write-Host '  演示账号初始化已关闭，请使用数据库中已有账号。' }
Write-Host ''
if ($demoEnabled -and $demoConfig.data.workflowEnabled -eq $true) {
    Write-Host '  已按数据库当天补齐演示数据：未来7天号源、今日诊疗示例和处方账单。'
    Write-Host '  patient 先选科室和医生，再选明日或其他日期；doctor 查看今日候诊示例。'
    Write-Host '  排班由 admin 分配；管理员工作台的补齐演示数据可继续补缺，不重置已操作状态。'
} else {
    Write-Host '  普通空库需先准备资源、发布排班；演示业务补齐未开启。'
    if ($demoEnabled) { Write-Host '  doctor 已绑定医生档案；用管理员安排并发布排班后患者即可预约。' }
}
Write-Host '  下次直接双击 启动MedFlow.cmd；停止时双击 停止MedFlow.cmd，数据库会保留。'
Write-Host ''
Write-Host '  停止：.\docker-start.ps1 -Down      清空数据：.\docker-start.ps1 -Reset' -ForegroundColor DarkGray
if ($OpenBrowser) { Start-Process "http://127.0.0.1:$appPort/" }
